"""Portable schema for Sakhi. SQLite today, Postgres in one pass.

WHY A SCHEMA MODULE INSTEAD OF INLINE SQL
------------------------------------------
The existing storage is split in two and neither half can move to Postgres as
written:

  - `mock_sixtydb.json` holds the live maternal data. A JSON file rewritten
    write-behind has no transactions, no constraints, and no concurrent-writer
    story. Two calls recording a BP for the same mother race on the whole file.
  - `db_helper.py` holds call reports in SQLite using `INTEGER PRIMARY KEY
    AUTOINCREMENT`, which is a SQLite-only spelling. Postgres rejects it
    outright, so "convert in one shot" was already impossible.

This module is the single place where dialect differences live. Everything
else - the repository, the tools, the agent - speaks plain DB-API and never
knows which database it is talking to.

THE PORTABILITY RULES, AND WHY EACH ONE EXISTS
-----------------------------------------------
1. **No AUTOINCREMENT.** SQLite's `INTEGER PRIMARY KEY` already auto-assigns;
   `AUTOINCREMENT` only changes rowid reuse and does not exist in Postgres.
   Rendered as `GENERATED BY DEFAULT AS IDENTITY` there.
2. **Timestamps are ISO-8601 TEXT, computed in Python.** Not
   `datetime('now')` (SQLite-only) and not `now()` (Postgres-only). A TEXT
   ISO-8601 column casts cleanly to `timestamptz` on migration, and storing
   UTC strings keeps the two backends byte-identical.
3. **Booleans are INTEGER 0/1.** SQLite has no boolean type; Postgres casts
   0/1 to BOOLEAN with an explicit `USING` clause on migration.
4. **Placeholders are rendered, never hardcoded.** SQLite uses `?`,
   psycopg uses `%s`. SQL text carries a neutral token.
5. **Every foreign key is declared** and `PRAGMA foreign_keys=ON` is set per
   connection - SQLite ignores FK declarations silently otherwise, which would
   let orphan BP readings accumulate and then fail the Postgres import.
"""

from __future__ import annotations

import dataclasses

PARAM = "?"          # neutral token used inside SQL text in this module


@dataclasses.dataclass(frozen=True)
class Dialect:
    """The complete set of differences between the two backends."""

    name: str
    placeholder: str
    identity_pk: str
    text: str
    # Postgres would use BOOLEAN; SQLite has no such type. Kept as INTEGER in
    # both so a migrated row compares equal without a rewrite.
    boolean: str

    def render(self, sql: str) -> str:
        """Translate neutral SQL text into this dialect."""
        if self.placeholder == PARAM:
            return sql
        return sql.replace(PARAM, self.placeholder)


SQLITE = Dialect(
    name="sqlite",
    placeholder="?",
    identity_pk="INTEGER PRIMARY KEY",
    text="TEXT",
    boolean="INTEGER",
)

# Defined now, unused until the migration. Keeping it here means the Postgres
# port is a one-line dialect swap plus the type-cast migration in
# `POSTGRES_MIGRATION_NOTES`, not a rewrite of every query.
POSTGRES = Dialect(
    name="postgres",
    placeholder="%s",
    identity_pk="BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
    text="TEXT",
    boolean="INTEGER",
)


def schema_statements(dialect: Dialect) -> list[str]:
    """DDL for a fresh database, in dependency order."""
    return [
        f"""
        CREATE TABLE IF NOT EXISTS mothers (
            patient_id        {dialect.text} PRIMARY KEY,
            name              {dialect.text} NOT NULL,
            age               INTEGER,
            village           {dialect.text},
            phone             {dialect.text},
            gestational_weeks INTEGER,
            risk_status       {dialect.text} NOT NULL DEFAULT 'ROUTINE',
            headache          {dialect.boolean} NOT NULL DEFAULT 0,
            blurry_vision     {dialect.boolean} NOT NULL DEFAULT 0,
            swelling          {dialect.boolean} NOT NULL DEFAULT 0,
            created_at        {dialect.text} NOT NULL,
            updated_at        {dialect.text} NOT NULL
        )
        """,
        # Immutable clinical log. Readings are never updated or deleted - a
        # corrected reading is a new row - because an amended blood pressure
        # with no history is indistinguishable from a falsified one.
        f"""
        CREATE TABLE IF NOT EXISTS bp_records (
            id           {dialect.identity_pk},
            patient_id   {dialect.text} NOT NULL REFERENCES mothers(patient_id),
            systolic     INTEGER NOT NULL,
            diastolic    INTEGER NOT NULL,
            risk_level   {dialect.text} NOT NULL,
            recorded_at  {dialect.text} NOT NULL
        )
        """,
        f"""
        CREATE TABLE IF NOT EXISTS symptom_records (
            id            {dialect.identity_pk},
            patient_id    {dialect.text} NOT NULL REFERENCES mothers(patient_id),
            headache      {dialect.boolean} NOT NULL DEFAULT 0,
            blurry_vision {dialect.boolean} NOT NULL DEFAULT 0,
            swelling      {dialect.boolean} NOT NULL DEFAULT 0,
            recorded_at   {dialect.text} NOT NULL
        )
        """,
        f"""
        CREATE TABLE IF NOT EXISTS teleconsults (
            id          {dialect.identity_pk},
            patient_id  {dialect.text} NOT NULL REFERENCES mothers(patient_id),
            channel_id  {dialect.text} NOT NULL,
            reason      {dialect.text},
            risk_level  {dialect.text},
            created_at  {dialect.text} NOT NULL
        )
        """,
        f"""
        CREATE TABLE IF NOT EXISTS call_reports (
            id              {dialect.identity_pk},
            session_id      {dialect.text},
            patient_id      {dialect.text},
            language        {dialect.text},
            risk_level      {dialect.text},
            intake_answered INTEGER NOT NULL DEFAULT 0,
            intake_total    INTEGER NOT NULL DEFAULT 0,
            escalated       {dialect.boolean} NOT NULL DEFAULT 0,
            duration_ms     INTEGER,
            created_at      {dialect.text} NOT NULL
        )
        """,
        # Lookup paths used on every call. Without these, `find_patients` is a
        # full scan - fine at 6 rows, not at 60,000 mothers in Bidar district.
        "CREATE INDEX IF NOT EXISTS idx_mothers_phone ON mothers(phone)",
        "CREATE INDEX IF NOT EXISTS idx_mothers_name ON mothers(name)",
        "CREATE INDEX IF NOT EXISTS idx_bp_patient ON bp_records(patient_id)",
        "CREATE INDEX IF NOT EXISTS idx_symptoms_patient ON symptom_records(patient_id)",
        "CREATE INDEX IF NOT EXISTS idx_teleconsults_patient ON teleconsults(patient_id)",
    ]


# Applied per connection, not per database: SQLite scopes both of these to the
# connection, and forgetting either is silent.
SQLITE_PRAGMAS = (
    # Without this, SQLite parses foreign keys and then ignores them.
    "PRAGMA foreign_keys = ON",
    # WAL lets readers proceed during a write. The agent reads on the hot path
    # of a live call; blocking a lookup behind another call's BP insert would
    # add latency to a clinical question.
    "PRAGMA journal_mode = WAL",
    # NORMAL is the documented safe pairing with WAL and avoids an fsync per
    # commit. FULL would put a disk sync in the middle of a voice turn.
    "PRAGMA synchronous = NORMAL",
    "PRAGMA busy_timeout = 5000",
)


POSTGRES_MIGRATION_NOTES = """
One-shot SQLite -> Postgres migration
=====================================

1. Point the dialect at POSTGRES. No query text changes: placeholders and the
   identity-column spelling are the only differences and both are rendered.

2. Create the schema:
       for stmt in schema_statements(POSTGRES): cur.execute(stmt)

3. Copy rows. Every column is TEXT/INTEGER in both backends, so a plain
   SELECT -> INSERT works with no transformation.

4. OPTIONAL type tightening, once the data is in:
       ALTER TABLE mothers
           ALTER COLUMN created_at TYPE timestamptz USING created_at::timestamptz,
           ALTER COLUMN updated_at TYPE timestamptz USING updated_at::timestamptz;
       ALTER TABLE mothers
           ALTER COLUMN headache TYPE boolean USING headache::int::boolean;
   The ISO-8601 TEXT and 0/1 INTEGER choices exist precisely so these casts are
   one-liners rather than data cleaning.

5. Reset identity sequences after a bulk copy that preserved ids:
       SELECT setval(pg_get_serial_sequence('bp_records','id'),
                     COALESCE(MAX(id),1)) FROM bp_records;

What is deliberately NOT used anywhere, because it would break this migration:
   AUTOINCREMENT, rowid, datetime()/julianday(), INSERT OR REPLACE,
   dynamic typing, and string concatenation with ||.
"""
