        f"ALTER TABLE mothers ADD COLUMN reduced_fetal_movement {dialect.boolean} NOT NULL DEFAULT 0",
        f"ALTER TABLE symptom_records ADD COLUMN convulsions {dialect.boolean} NOT NULL DEFAULT 0",
