"""SQLite repository + Postgres portability of the schema.

The storage was split in two before this: mock_sixtydb.json for maternal data
(write-behind, no transactions, no crash durability) and db_helper.py's SQLite
for call reports using AUTOINCREMENT - a SQLite-only spelling that Postgres
rejects, so "convert in one shot" was already impossible.
"""

import asyncio
import json
import sqlite3

import pytest

from sakhi_domain import BloodPressure, RiskLevel, SymptomSet
from sakhi_repository import PatientRepository
from sakhi_schema import POSTGRES, SQLITE, schema_statements
from sakhi_sql_repository import SQLitePatientRepository
from sakhi_triage import TRIAGE


def _run(coro):
    return asyncio.run(coro)


@pytest.fixture
def repo(tmp_path):
    return _run(SQLitePatientRepository(tmp_path / "t.sqlite3").load())


# --- the seam --------------------------------------------------------------

def test_it_is_a_drop_in_for_the_abc(repo):
    """Swapping storage must change no call site - that is why the ABC exists."""
    assert isinstance(repo, PatientRepository)
    for method in ("find_patients", "get_patient", "create_patient",
                   "record_blood_pressure", "record_symptoms", "log_teleconsult", "close"):
        assert callable(getattr(repo, method))


# --- Postgres portability --------------------------------------------------

def test_schema_uses_nothing_sqlite_only():
    """Each of these would break the one-shot Postgres migration."""
    ddl = " ".join(schema_statements(SQLITE)).upper()
    for banned in ("AUTOINCREMENT", "ROWID", "DATETIME(", "JULIANDAY(", "INSERT OR REPLACE"):
        assert banned not in ddl, f"{banned} is SQLite-only and blocks the Postgres port"


def test_schema_renders_for_postgres_without_editing_queries():
    pg = " ".join(schema_statements(POSTGRES))
    assert "GENERATED BY DEFAULT AS IDENTITY" in pg
    assert "AUTOINCREMENT" not in pg.upper()


def test_placeholders_are_rendered_not_hardcoded():
    """sqlite3 uses ?, psycopg uses %s. SQL text carries a neutral token."""
    assert SQLITE.render("SELECT * FROM mothers WHERE patient_id = ?") == \
        "SELECT * FROM mothers WHERE patient_id = ?"
    assert POSTGRES.render("SELECT * FROM mothers WHERE patient_id = ?") == \
        "SELECT * FROM mothers WHERE patient_id = %s"


def test_every_table_exists_after_load(repo, tmp_path):
    conn = sqlite3.connect(str(tmp_path / "t.sqlite3"))
    names = {r[0] for r in conn.execute("SELECT name FROM sqlite_master WHERE type='table'")}
    conn.close()
    assert {"mothers", "bp_records", "symptom_records",
            "teleconsults", "call_reports"} <= names


def test_foreign_keys_are_actually_enforced(repo):
    """SQLite parses FK declarations and then IGNORES them unless the pragma is
    set per connection. Without it, orphan BP rows accumulate and only surface
    as a failed Postgres import much later."""
    async def go():
        with pytest.raises(sqlite3.IntegrityError):
            await repo.record_blood_pressure(
                "M-DOES-NOT-EXIST", BloodPressure(120, 80),
                TRIAGE.assess(BloodPressure(120, 80), SymptomSet()),
            )
    _run(go())


# --- behaviour -------------------------------------------------------------

def test_create_find_and_history_round_trip(repo):
    async def go():
        m = await repo.create_patient(name="Suma Gowda", age=24, village="Kamalnagar",
                                      phone="9876543210", gestational_weeks=28)
        assert m.patient_id.startswith("M-")

        bp = BloodPressure(145, 95)
        await repo.record_blood_pressure(m.patient_id, bp, TRIAGE.assess(bp, SymptomSet()))

        found = await repo.find_patients(name="suma")
        assert len(found) == 1
        assert found[0].name == "Suma Gowda"
        assert len(found[0].history) == 1
        assert found[0].history[0]["bp"] == "145/95"
    _run(go())


def test_risk_status_and_reading_move_together(repo):
    """A committed reading with a stale risk status is the de-sync that made
    triage disagree with the record it was computed from."""
    async def go():
        m = await repo.create_patient(name="Priya Patil", age=29)
        bp = BloodPressure(165, 115)
        assessment = TRIAGE.assess(bp, SymptomSet())
        await repo.record_blood_pressure(m.patient_id, bp, assessment)

        fetched = await repo.get_patient(m.patient_id)
        assert fetched.risk_status is assessment.level
        assert fetched.risk_status is RiskLevel.HIGH_RISK
    _run(go())


def test_symptoms_accumulate_and_never_clear(repo):
    """A later 'no headache' must not erase one the mother already reported."""
    async def go():
        m = await repo.create_patient(name="Suma Gowda")
        await repo.record_symptoms(m.patient_id, SymptomSet(headache=True))
        await repo.record_symptoms(m.patient_id, SymptomSet(swelling=True))

        fetched = await repo.get_patient(m.patient_id)
        assert fetched.symptoms.headache, "an earlier reported symptom was erased"
        assert fetched.symptoms.swelling
    _run(go())


def test_a_spoken_name_with_sql_in_it_is_data_not_sql(repo):
    async def go():
        await repo.create_patient(name="Suma Gowda")
        found = await repo.find_patients(name="' OR '1'='1")
        assert found == [], "LIKE pattern was concatenated instead of bound"
        # And the table survived.
        assert await repo.find_patients(name="Suma")
    _run(go())


def test_writes_survive_a_crash_before_any_explicit_flush(tmp_path):
    """The JSON store's write-behind window loses a severe reading if the
    worker dies inside it. A committed row is on disk immediately."""
    async def go():
        path = tmp_path / "durable.sqlite3"
        repo = await SQLitePatientRepository(path).load()
        m = await repo.create_patient(name="Suma Gowda")
        bp = BloodPressure(160, 110)
        await repo.record_blood_pressure(m.patient_id, bp, TRIAGE.assess(bp, SymptomSet()))
        # No close(), no flush() - a separate connection, as a restarted worker.
        fresh = await SQLitePatientRepository(path).load()
        stats = await fresh.stats()
        assert stats["mothers"] == 1
        assert stats["bp_records"] == 1, "the 160/110 reading was lost"
    _run(go())


def test_concurrent_registrations_all_persist(repo):
    async def go():
        await asyncio.gather(*(
            repo.create_patient(name=f"Mother {i}", age=25) for i in range(20)
        ))
        stats = await repo.stats()
        assert stats["mothers"] == 20, "ids collided or writes were lost"
    _run(go())


def test_phone_lookup_normalises(repo):
    async def go():
        await repo.create_patient(name="Suma Gowda", phone="98765-43210")
        assert await repo.find_patients(phone="9876543210")
    _run(go())
